/* Lift the pure functions out of the built app into dist/lib.js, so they can be
 * tested in Node without a browser.
 *
 * The app is one file with no module system; that is a feature, not an
 * oversight. But a function that maps bytes to bytes does not need a DOM to be
 * tested, and testing it through jsdom would be slower and weaker. So: parse
 * the built file with acorn, cut out the top-level declarations that are pure,
 * and wrap them in a module that assigns to globalThis.KB.
 *
 * The app keeps its own copy — this is the same source text, extracted, not a
 * fork. `node test/lib.js` proves the extraction still matches.
 *
 * Usage: node tools/build-lib.js [--check]
 */
const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const ROOT = path.join(__dirname, '..');
const APP = path.join(ROOT, 'kitbox.html');
const OUT = path.join(ROOT, 'dist', 'lib.js');
const CHECK = process.argv.includes('--check');

const PURE = [
  'escapeHtml', 'fmtBytes', 'fmtNum', 'crc32', 'CRC32_TABLE', 'buildZip',
  'md5', 'toBase32', 'fromBase32', 'toBase58', 'fromBase58', 'B32', 'B58',
  'passStrength', 'contrastWith', 'tileLuminance',
  'readOrientation', 'minimalExif', 'stripJpegMetadata',
  'bytesFromText', 'textFromBytes', 'ASTRO',
  'ASN1_TYPES', 'asn1Oid', 'parseASN1', 'asn1Rows'
];

const html = fs.readFileSync(APP, 'utf8');
const script = html.slice(html.indexOf('<script>') + 8, html.lastIndexOf('</script>'));

const ast = acorn.parse(script, { ecmaVersion: 'latest', sourceType: 'script' });
const found = new Map();
for (const node of ast.body) {
  if (node.type === 'FunctionDeclaration' && node.id) {
    found.set(node.id.name, [node.start, node.end]);
  } else if (node.type === 'VariableDeclaration') {
    for (const d of node.declarations) {
      if (d.id.type === 'Identifier') found.set(d.id.name, [node.start, node.end]);
    }
  }
}

const missing = PURE.filter(n => !found.has(n));
if (missing.length) {
  console.error('not found at top level: ' + missing.join(', '));
  process.exit(1);
}

const body = PURE.map(n => {
  const [s, e] = found.get(n);
  return script.slice(s, e);
}).join('\n\n');

const lib = `/* Generated by tools/build-lib.js from kitbox.html — do not edit.
 *
 * The pure functions of Kitbox, extracted so they can be tested in Node.
 * ${PURE.length} declarations: ${PURE.join(', ')}
 */
(function (global) {
'use strict';
${body}

global.KB = { ${PURE.join(', ')} };
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });

if (CHECK) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== lib) {
    console.log('FAIL  dist/lib.js is out of date — run node tools/build-lib.js');
    process.exit(1);
  }
  console.log('PASS  dist/lib.js matches the app (' + PURE.length + ' functions)');
  process.exit(0);
}

fs.writeFileSync(OUT, lib);
console.log('dist/lib.js — ' + PURE.length + ' functions, ' + lib.length + ' bytes');
